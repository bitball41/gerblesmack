class Sprite:
    def __init__(self):
        self.im = Image.new('RGBA', (32, 32))
        self.d = ImageDraw.Draw(self.im)

    def r(self, box, color, outline=None):
        self.d.rectangle(box, fill=color, outline=outline)

    def p(self, pts, color, outline=None):
        self.d.polygon(pts, fill=color, outline=outline)

    def l(self, pts, color, width=1):
        self.d.line(pts, fill=color, width=width)

    def e(self, box, color, outline=None):
        self.d.ellipse(box, fill=color, outline=outline)

    def star(self, x, y, color=WHITE):
        self.l([(x-2, y), (x+2, y)], color)
        self.l([(x, y-2), (x, y+2)], color)

    def save(self, name):
        self.im.save(ART / (name + '.png'), optimize=True)


